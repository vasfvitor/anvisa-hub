// Contract with the `anvisa-api` pipeline (manifest schema_version 1), reduced to what the hub shows:
// build id and time, generator, docs link and, per table, title, rows and the source's load date.
// Table paths change every build and are never used here; the hub links the Pages index instead.

export interface Source {
  name: string;
  url: string;
  loaded_at?: string | null;
}

export interface Table {
  title?: string;
  path: string;
  rows: number;
  source: Source;
}

export interface Manifest {
  schema_version: number;
  build_id: string;
  built_at: string;
  generator?: string;
  /** data dictionary generated by the pipeline, relative to the manifest (dicionario.html) */
  docs?: string;
  tables: Record<string, Table>;
}

const TABLE_NAME = /^[a-z_][a-z0-9_]*$/;

/**
 * Keeps what the hub uses. An unknown schema_version fails loudly, since it means the contract moved;
 * a table without a path, a source or a row count is left out, since the pipeline may publish tables
 * before the hub knows them.
 */
export function parseManifest(raw: unknown): Manifest {
  const m = raw as Partial<Manifest> | null;
  if (!m || typeof m !== "object") throw new Error("manifest: not an object");
  if (m.schema_version !== 1) throw new Error(`manifest: schema_version ${m.schema_version} (expected 1)`);
  if (typeof m.build_id !== "string" || typeof m.built_at !== "string") throw new Error("manifest: no build_id");
  if (!m.tables || typeof m.tables !== "object") throw new Error("manifest: no tables");
  const rawTables: Record<string, Partial<Table> | null> = m.tables;
  const tables: Record<string, Table> = {};
  for (const [name, t] of Object.entries(rawTables)) {
    if (!TABLE_NAME.test(name) || typeof t?.path !== "string" || typeof t.source !== "object") continue;
    if (typeof t.rows !== "number") continue;
    tables[name] = t as Table;
  }
  return { ...(m as Manifest), tables };
}

/** The most recent `loaded_at` across the tables, or null when no table carries one. */
export function latestLoadedAt(m: Manifest): string | null {
  const dates = Object.values(m.tables)
    .map((t) => t.source.loaded_at)
    .filter((d): d is string => typeof d === "string" && d.length > 0);
  return dates.length ? dates.reduce((a, b) => (a > b ? a : b)) : null;
}

/** Absolute URL of a file published beside the manifest (the Pages index, the data dictionary). */
export function besideManifest(manifestUrl: string, path: string): string {
  return new URL(path, manifestUrl).href;
}

/** `?t=` gets past the 600 s cache of GitHub Pages, so a build never reads a stale manifest. */
export async function fetchManifest(manifestUrl: string): Promise<Manifest> {
  const u = new URL(manifestUrl);
  u.searchParams.set("t", String(Date.now()));
  const res = await fetch(u, { cache: "no-store" });
  if (!res.ok) throw new Error(`manifest: HTTP ${res.status} at ${manifestUrl}`);
  return parseManifest(await res.json());
}

let forBuild: Promise<Manifest> | undefined;
/** One fetch per build, shared by every page and endpoint. */
export function manifestForBuild(manifestUrl: string): Promise<Manifest> {
  return (forBuild ??= fetchManifest(manifestUrl));
}
